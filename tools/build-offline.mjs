/* Run after changing any shipped file: node tools/build-offline.mjs
   Commit sw.js as well, so both direct static hosting and Actions work without npm. */
import {readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {resolve, dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const digest=body=>createHash('sha256').update(body).digest('hex');
function walk(dir){
  return readdirSync(join(root,dir),{withFileTypes:true}).flatMap(entry=>{
    const name=dir+'/'+entry.name;
    return entry.isDirectory()?walk(name):[name];
  });
}
const files=['index.html','manifest.webmanifest',...walk('src'),...walk('css'),...walk('assets')]
  .filter(file=>/\.(html|webmanifest|js|css|png|svg|woff2)$/.test(file)).sort();
const assets=files.map(url=>{
  const body=readFileSync(join(root,url));
  return {url,sha256:digest(body),bytes:body.length};
});
const runtime=readFileSync(join(root,'tools/service-worker.js'),'utf8');
const version=digest(JSON.stringify(assets)+runtime).slice(0,20);
const output='/* Generated by tools/build-offline.mjs — do not edit directly. */\n'+
  `const OFFLINE_VERSION=${JSON.stringify(version)};\n`+
  `const OFFLINE_ASSETS=${JSON.stringify(assets,null,2)};\n\n`+runtime;
const target=join(root,'sw.js');
if(process.argv.includes('--check')){
  let current='';
  try{current=readFileSync(target,'utf8');}catch{}
  if(current!==output){
    console.error('sw.js 已過期；請執行 node tools/build-offline.mjs 並提交產出的 sw.js。');
    process.exitCode=1;
  }else console.log(`Offline manifest OK: ${files.length} files, version ${version}`);
}else{
  writeFileSync(target,output);
  console.log(`Generated sw.js: ${files.length} files, ${assets.reduce((n,a)=>n+a.bytes,0)} bytes, version ${version}`);
}
